#!/usr/bin/env python3

"""Generate kitty-diacritics.h from the kitty row/column diacritics list.

Input: the 'rowcolumn-diacritics.txt' file that the kitty graphics
protocol documentation links to:

    https://sw.kovidgoyal.net/kitty/graphics-protocol/

Each code point line has the form 'XXXX;NAME;...'. Comments start with
'#'. The generated header is committed, so the build has no network
step (design D9). Regenerate it with:

    scripts/generate-kitty-diacritics.py rowcolumn-diacritics.txt \\
        kitty-diacritics.h
"""

import argparse

# The list holds one diacritic for every value 0..296.
EXPECTED_COUNT = 297

# Kitty anchors: the first three row/column values.
ANCHORS = (0x0305, 0x030D, 0x030E)


def read_lines(path: str) -> list[str]:
    try:
        with open(path, encoding='utf-8') as f:
            return f.readlines()
    except OSError as e:
        raise SystemExit(f'cannot read {path}: {e}') from e


def write_header(path: str, codepoints: list[int]) -> None:
    try:
        with open(path, 'w', encoding='utf-8') as out:
            out.write('#pragma once\n')
            out.write('\n')
            out.write('#include <stdint.h>\n')
            out.write('\n')
            out.write('/*\n')
            out.write(' * Row/column diacritics for Unicode image placeholders\n')
            out.write(' * (design D9).\n')
            out.write(' *\n')
            out.write(' * Generated by scripts/generate-kitty-diacritics.py from\n')
            out.write(' * the rowcolumn-diacritics.txt file of the kitty graphics\n')
            out.write(' * protocol documentation:\n')
            out.write(' *\n')
            out.write(' *   https://sw.kovidgoyal.net/kitty/graphics-protocol/\n')
            out.write(' *\n')
            out.write(' * The table is sorted by code point. The index of a code\n')
            out.write(' * point is its row/column value.\n')
            out.write(' */\n')
            out.write('\n')
            out.write(f'#define KITTY_DIACRITICS_COUNT {EXPECTED_COUNT}\n')
            out.write('\n')
            out.write('static const uint32_t '
                      'kitty_diacritics[KITTY_DIACRITICS_COUNT] = {\n')

            for i in range(0, len(codepoints), 8):
                chunk = codepoints[i:i + 8]
                values = ', '.join(f'0x{cp:04x}' for cp in chunk)
                out.write(f'    {values},\n')

            out.write('};\n')
            out.write('\n')
            out.write('/*\n')
            out.write(' * Index of \'cp\' in kitty_diacritics[], or -1 when it\n')
            out.write(' * is not a row/column diacritic. Binary search (design\n')
            out.write(' * D9).\n')
            out.write(' */\n')
            out.write('int kitty_diacritic_index(uint32_t cp);\n')
    except OSError as e:
        raise SystemExit(f'cannot write {path}: {e}') from e


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('input', type=str)
    parser.add_argument('output', type=str)
    opts = parser.parse_args()

    codepoints: list[int] = []
    for line in read_lines(opts.input):
        line = line.rstrip()
        if not line or line[0] == '#':
            continue
        code = line.split(';', maxsplit=1)[0]
        codepoints.append(int(code, 16))

    assert codepoints == sorted(codepoints), 'input is not sorted'
    assert len(codepoints) == EXPECTED_COUNT, (
        f'expected {EXPECTED_COUNT} diacritics, got {len(codepoints)}')
    assert tuple(codepoints[:len(ANCHORS)]) == ANCHORS, (
        f'unexpected anchors: {codepoints[:len(ANCHORS)]}')

    write_header(opts.output, codepoints)


if __name__ == '__main__':
    main()
